import 'package:dart_architecture_lints/streamcontroller_must_close.dart';
import 'package:test/test.dart';
import '../tool/generate_rule_tables.dart' as generator;
import 'rule_test_support.dart';

void main() {
  for (final wrapper in [
    '(external)',
    '((external))',
    '(external!)',
    '(external as StreamController<int>)',
    '((external!) as StreamController<int>)',
  ]) {
    test(
      'field and constructor references remain borrowed: $wrapper',
      () async {
        final result = await runRule(const StreamControllerMustClose(), '''
import 'dart:async';
final StreamController<int>? external = StreamController<int>();
class ChangeNotifier { void dispose() {} }
class FieldBorrower extends ChangeNotifier {
  final StreamController<int>? controller = $wrapper;
}
class ConstructorBorrower extends ChangeNotifier {
  ConstructorBorrower() : controller = $wrapper;
  final StreamController<int>? controller;
}
''');
        expect(result, isEmpty);
      },
    );
  }
  test(
    'wrapping construction does not turn an owned resource into borrowed',
    () async {
      expect(
        await runRule(const StreamControllerMustClose(), '''
import 'dart:async';
class ChangeNotifier { void dispose() {} }
class Owner extends ChangeNotifier {
  final StreamController<int> controller = ((StreamController<int>()) as StreamController<int>);
}
'''),
        hasLength(1),
      );
    },
  );
  for (final marker in [
    'AUTOGENERATED:RULE_TOTAL_COUNTS',
    'AUTOGENERATED:Core Language Rules',
  ]) {
    final open = '<!-- $marker -->';
    final close = '<!-- END $marker -->';
    test('README $marker requires exactly one ordered marker pair', () {
      expect(
        generator.replaceSection('$open\nold\n$close', marker, 'new'),
        '$open\nnew\n$close',
      );
      for (final source in [
        '',
        '$open only',
        '$close only',
        '$close\n$open',
        '$open\n$open\n$close',
        '$open\n$close\n$close',
        '$open\n$close\n$open\n$close',
      ]) {
        expect(
          () => generator.replaceSection(source, marker, 'new'),
          throwsFormatException,
        );
      }
    });
  }
}
